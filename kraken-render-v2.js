// kraken-render-v2.js — the rebuilt, properly Terraria-styled Kraken render().
//
// WHY THIS EXISTS: the previous render multiplied a single `power` ladder
// (1 + (phase-1)*1.7) into body width, limb width, reach AND the aura radius.
// At phase 4 that was a 6.1x blow-up — a 2100px body inside an 1860px-radius
// violet aura that filled the screen and washed every tile out ("it gets
// bigger and bigger, blocks go invisible"). This version DECOUPLES the three
// concerns the old one tangled together:
//   * grow    — a small, HARD-CAPPED visual scale (1.0 -> 1.35). The beast
//               reads a little bigger each phase but never explodes.
//   * heat    — a phase "temperature" that only recolours (palette + glow),
//               never geometry.
//   * motion  — the whole-body swim/coil/lunge, all bounded springs.
//
// STYLE: true Terraria. Flat quantised tone bands, hard pixel outlines snapped
// to a 2px grid, NO soft radial gradients on the body, square sucker pixels,
// and a strictly SYMMETRIC face — both eyes share one centre row, one radius,
// one pupil. It is meant to sit next to chunky tile sprites, not float like a
// watercolour. Exported as an array of source lines so a patch script can
// splice it into the class verbatim.
